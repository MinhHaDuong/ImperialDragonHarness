"""Resident rules as one instruction file for Codex and Pi (ticket 1413).

Only Claude Code loads rules/ by itself. Codex reads ~/.codex/AGENTS.md and Pi
~/.pi/agent/AGENTS.md; neither strips HTML comments. The generated file holds
the resident rules (resident_census.is_auto_loaded) minus claude-code.md, with
comments stripped. Never hand-edited: a destination without MARKER on its
first line is left alone and reported.
"""

import os
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import resident_census as rc  # noqa: E402

MARKER = "Generated by scripts/runtime_rules.py from rules/ (idh install); do not edit.\n"
SKIP = {"claude-code.md"}


def resident(rules: Path) -> list[Path]:
    return [p for p in sorted(rules.rglob("*.md")) if p.name not in SKIP and rc.is_auto_loaded(p)]


def build(rules: Path) -> str:
    bodies = [rc.loaded_rule_text(p).strip("\n") + "\n" for p in resident(rules)]
    return MARKER + "\n" + "\n".join(bodies)


def write(rules: Path, dest: Path) -> str:
    """skipped (runtime absent) | refused (hand-written) | unchanged | written."""
    if not dest.parent.is_dir():
        return "skipped"
    text = build(rules)
    if dest.exists():
        old = dest.read_text(encoding="utf-8")
        if not old.startswith(MARKER):
            return "refused"
        if old == text:
            return "unchanged"
    fd, name = tempfile.mkstemp(dir=dest.parent, prefix=".AGENTS.idh-tmp-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(text)
        os.chmod(name, 0o644)
        os.replace(name, dest)
    except BaseException:
        Path(name).unlink(missing_ok=True)
        raise
    return "written"
